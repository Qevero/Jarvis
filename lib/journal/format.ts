import { formatUkDate } from "@/lib/dates";

/** Journal helpers: action items, blog draft export, themes over time. Pure. */

export type ActionItem = { text: string; due?: string | null; pushed_task_id?: string | null; done?: boolean };

export type JournalEntry = {
  id: string;
  entry_date: string;
  title: string;
  raw_notes: string | null;
  summary: string | null;
  themes: string[];
  decisions: string[];
  ideas: string[];
  action_items: ActionItem[];
  linked_clients: string[];
  source?: string;
  created_at?: string;
};

export function normaliseTags(input: (string | null | undefined)[] | null | undefined): string[] {
  const out = new Set<string>();
  for (const t of input ?? []) {
    const n = (t ?? "").trim().toLowerCase().replace(/^#/, "").replace(/\s+/g, " ");
    if (n) out.add(n.slice(0, 60));
  }
  return [...out].slice(0, 20);
}

export function slugify(title: string): string {
  return title.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 80) || "post";
}

/**
 * A starting-point blog draft for qevero.com, assembled from the entry (no AI).
 * Client names are left out by default: Jarvis never publishes client details.
 */
export function blogDraftMarkdown(e: JournalEntry, opts: { includeClients?: boolean } = {}): string {
  const lines: string[] = [];
  lines.push("---");
  lines.push(`title: "${e.title.replace(/"/g, "'")}"`);
  lines.push(`slug: ${slugify(e.title)}`);
  lines.push(`date: ${e.entry_date}`);
  lines.push(`tags: [${e.themes.map((t) => `"${t}"`).join(", ")}]`);
  lines.push("status: draft");
  lines.push("author: Jasper Sayer");
  lines.push("---");
  lines.push("");
  lines.push(`# ${e.title}`);
  lines.push("");
  lines.push("<!-- Draft generated by Jarvis from a journal entry. Edit before publishing; check nothing confidential remains. -->");
  lines.push("");
  if (e.summary) {
    lines.push(e.summary.trim());
    lines.push("");
  }
  if (e.ideas.length) {
    lines.push("## Ideas worth sharing");
    lines.push("");
    for (const i of e.ideas) lines.push(`- ${i}`);
    lines.push("");
  }
  if (e.decisions.length) {
    lines.push("## What we decided, and why");
    lines.push("");
    for (const d of e.decisions) lines.push(`- ${d}`);
    lines.push("");
  }
  if (opts.includeClients && e.linked_clients.length) {
    lines.push(`_Related work: ${e.linked_clients.join(", ")}_`);
    lines.push("");
  }
  if (e.raw_notes && !e.summary) {
    lines.push("## Notes");
    lines.push("");
    lines.push(e.raw_notes.trim());
    lines.push("");
  }
  lines.push("---");
  lines.push("");
  lines.push("_Qevero builds websites, SEO/GEO and software for growing businesses. [Get in touch](https://qevero.com)._");
  lines.push("");
  return lines.join("\n");
}

/** Pivot theme counts into a month × theme table, top themes first. */
export function themesOverTime(rows: { month: string; theme: string; entries: number }[], topN = 8) {
  const totals = new Map<string, number>();
  for (const r of rows) totals.set(r.theme, (totals.get(r.theme) ?? 0) + Number(r.entries));
  const top = [...totals.entries()].sort((a, b) => b[1] - a[1]).slice(0, topN).map(([t]) => t);
  const months = [...new Set(rows.map((r) => r.month))].sort();
  return {
    themes: top.map((t) => ({ theme: t, total: totals.get(t)! })),
    months: months.map((m) => ({
      month: m,
      counts: Object.fromEntries(top.map((t) => [t, Number(rows.find((r) => r.month === m && r.theme === t)?.entries ?? 0)])),
    })),
  };
}

export function entryToText(e: JournalEntry): string {
  const parts = [`${formatUkDate(e.entry_date)} — ${e.title}`];
  if (e.summary) parts.push(e.summary);
  if (e.decisions.length) parts.push(`Decisions: ${e.decisions.join("; ")}`);
  if (e.ideas.length) parts.push(`Ideas: ${e.ideas.join("; ")}`);
  if (e.action_items.length) parts.push(`Actions: ${e.action_items.map((a) => a.text).join("; ")}`);
  return parts.join("\n");
}
